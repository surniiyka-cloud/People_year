create schema if not exists people;
revoke all on schema people from public, anon, authenticated;
create table people.employee(id text primary key,name text not null,city text not null,active integer not null default 1 check(active in (0,1)));
create table people.season(year integer primary key,status text not null default 'draft' check(status in ('draft','open','closed')),is_test integer not null default 0 check(is_test in (0,1)));
create table people.participation(year integer references people.season,employee text references people.employee,code_hash text unique,used integer not null default 0 check(used in (0,1)),primary key(year,employee));
create table people.ballot(id text primary key,year integer not null references people.season,candidate text not null references people.employee);
create table people.archive_batch(id text primary key,label text not null);
create table people.archive_name(batch text references people.archive_batch,raw text not null,n integer not null check(n>0),employee text references people.employee,primary key(batch,raw));
create table people.session(token_hash text primary key,role text not null check(role in ('admin','voter')),year integer,employee text,code_hash text,expires timestamptz not null);
create table people.rate_limit(key text primary key,started timestamptz not null,attempts integer not null);
alter table people.employee enable row level security;
alter table people.season enable row level security;
alter table people.participation enable row level security;
alter table people.ballot enable row level security;
alter table people.archive_batch enable row level security;
alter table people.archive_name enable row level security;
alter table people.session enable row level security;
alter table people.rate_limit enable row level security;
revoke all on all tables in schema people from public,anon,authenticated;